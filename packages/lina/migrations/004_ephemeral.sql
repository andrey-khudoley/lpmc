-- Непрозрачные срочные значения (W2-LINA-02).
--
-- Одноразовая ссылка подтверждения — именно такое значение: она действует
-- считанные минуты, годится один раз и не должна оставаться в истории диалога.
-- Хранить её «на всякий случай» означало бы, что доступ к базе адаптера даёт
-- доступ к подтверждению необратимого действия.
--
-- Поэтому текст такого сообщения показывается ОДИН раз и стирается. Просьба
-- человека «пришли ещё раз» не выдаёт его повторно: новое значение выдаёт
-- только новое решение арбитра (D-021, LINA L-13).
ALTER TABLE deliveries ADD COLUMN IF NOT EXISTS ephemeral boolean NOT NULL DEFAULT false;
ALTER TABLE deliveries ADD COLUMN IF NOT EXISTS revealed_at timestamptz;
