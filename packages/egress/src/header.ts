/**
 * Пригодность значения к отправке в заголовке.
 *
 * Node проверяет значение сам, но делает это СИНХРОННО в конструкторе
 * `ClientRequest` и бросает `ERR_INVALID_CHAR`. Обработчик `error`, навешенный
 * на запрос, до этого момента не существует и такое не ловит: непроверенное
 * значение снимает процесс целиком. Для прокси это означает не отказ одному
 * запуску, а прекращение единственного пути наружу сразу для всех контуров,
 * поэтому значение проверяется здесь, до построения запроса.
 *
 * Набор допустимых символов повторяет проверку Node (`headerCharRegex`):
 * табуляция и печатные символы latin1. Перевод строки недопустим не только
 * потому, что его запрещает Node: им заголовок расщепляется на два, и значение,
 * пришедшее из внешней системы, дописывало бы к запросу произвольные поля.
 */
export function isLegalHeaderValue(value: string): boolean {
  return /^[\t\x20-\x7e\x80-\xff]*$/.test(value);
}
