-- Общий диалог с Линой («входящие»).
--
-- До этого Лина жила только внутри конкретной задачи: диалог открывался по уже
-- существующей задаче и правил её поля. Здесь заводится общий разговор, не
-- привязанный к задаче: оператор описывает задачу словами, Лина квалифицирует
-- (тема + владелец), при нехватке — переспрашивает, а когда достаточно — создаёт
-- задачу (web_tasks) и продолжает уточнение уже в её собственном диалоге.
--
-- Одна лента на инсталляцию: это рабочий стол оператора, а не переписка на
-- каждого пользователя. Черновик незавершённой квалификации не хранится
-- отдельной таблицей — он лежит в payload последнего вопроса Лины (поле draft),
-- как и признак «жду ответа» (awaiting), тем же приёмом, что вопросы в диалоге
-- задачи (web_messages).

CREATE TABLE IF NOT EXISTS web_inbox (
  id         bigserial PRIMARY KEY,
  kind       text        NOT NULL,                 -- you | reply | note
  payload    jsonb       NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
