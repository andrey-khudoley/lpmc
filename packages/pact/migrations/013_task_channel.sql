-- Канал и адаптер задачи.
--
-- Прежде они были известны только в момент приёма и жили в разборе диспетчера.
-- Подтверждение необратимого действия приходит позже — иногда через часы, —
-- и арбитру нужно знать, куда отправить ссылку. Восстанавливать это из разбора
-- значило бы держать разбор вечно.
ALTER TABLE tasks ADD COLUMN IF NOT EXISTS channel text;
ALTER TABLE tasks ADD COLUMN IF NOT EXISTS adapter_id text;

-- Подтверждение записывается в ЛИЗИНГ, а не в задачу: оно действительно ровно
-- для одного запуска, и следующий обязан получать своё (MITA §5.6.3, п. 3).
ALTER TABLE leases ADD COLUMN IF NOT EXISTS approval_id uuid;
