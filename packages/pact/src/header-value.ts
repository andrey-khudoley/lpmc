/**
 * Пригодность значения к отправке в заголовке HTTP.
 *
 * Снимок сессии подставляется прокси в заголовок `Cookie` (W2-MITA-01), поэтому
 * значение, непригодное как заголовок, непригодно и как снимок. Проверка стоит
 * здесь, на приёме, а не только у прокси: снимок, принятый в custody, обязан
 * быть работоспособным, иначе отказ придёт не оператору, вносящему его, а
 * запуску через неопределённое время после внесения.
 *
 * Набор допустимых символов повторяет проверку Node (`headerCharRegex`):
 * табуляция и печатные символы latin1. Перевод строки недопустим не только
 * потому, что его запрещает Node: им заголовок расщепляется на два, и снимок,
 * снятый с внешней системы, дописывал бы к запросу произвольные поля.
 *
 * Тот же перечень продублирован в прокси (`egress/src/header.ts`): он живёт в
 * другом репозитории и общего кода с этим пакетом не имеет. Расхождение двух
 * перечней означало бы снимок, принятый здесь и отклонённый там, поэтому оба
 * сверяются с поведением Node в своих тестах, а не друг с другом.
 */
export function isLegalHeaderValue(value: string): boolean {
  return /^[\t\x20-\x7e\x80-\xff]*$/.test(value);
}
